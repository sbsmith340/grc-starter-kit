"""
Validate the risk register and produce a heat map and top-risks summary.

  python tools/risk_report.py register/risk_register.csv            # writes register/REPORT.md
  python tools/risk_report.py register/risk_register.csv --check    # validate only (CI)
"""
from __future__ import annotations

import argparse
import csv
import sys
from datetime import date
from pathlib import Path

CIA = {"Low", "Moderate", "High"}
TREATMENTS = {"Mitigate", "Transfer", "Avoid", "Accept"}
STATUSES = {"Planned", "In progress", "Complete", "Accepted"}
APPETITE = 11  # residual scores above this exceed appetite
REQUIRED = ["RiskId", "Title", "Description", "Asset", "Confidentiality", "Integrity", "Availability",
            "Likelihood", "Impact", "Treatment", "RecommendedControls", "ResidualLikelihood",
            "ResidualImpact", "Owner", "Status", "ReviewDate"]


def rating(score: int) -> str:
    return "Critical" if score >= 20 else "High" if score >= 12 else "Medium" if score >= 6 else "Low"


def load(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def enrich(r: dict) -> dict:
    r = dict(r)
    r["Inherent"] = int(r["Likelihood"]) * int(r["Impact"])
    r["Residual"] = int(r["ResidualLikelihood"]) * int(r["ResidualImpact"])
    r["InherentRating"], r["ResidualRating"] = rating(r["Inherent"]), rating(r["Residual"])
    return r


def validate(rows: list[dict], today: date | None = None) -> list[str]:
    today = today or date.today()
    errs, seen = [], set()
    for i, r in enumerate(rows, start=2):  # header is line 1
        rid = r.get("RiskId") or f"line {i}"
        for k in REQUIRED:
            if not (r.get(k) or "").strip():
                errs.append(f"{rid}: missing {k}")
        if errs and errs[-1].startswith(rid):
            continue
        if rid in seen:
            errs.append(f"{rid}: duplicate RiskId")
        seen.add(rid)
        for k in ("Confidentiality", "Integrity", "Availability"):
            if r[k] not in CIA:
                errs.append(f"{rid}: {k} must be Low/Moderate/High")
        for k in ("Likelihood", "Impact", "ResidualLikelihood", "ResidualImpact"):
            if not r[k].isdigit() or not 1 <= int(r[k]) <= 5:
                errs.append(f"{rid}: {k} must be 1-5")
        if r["Treatment"] not in TREATMENTS:
            errs.append(f"{rid}: Treatment must be one of {sorted(TREATMENTS)}")
        if r["Status"] not in STATUSES:
            errs.append(f"{rid}: Status must be one of {sorted(STATUSES)}")
        if any(e.startswith(rid) for e in errs):
            continue
        e = enrich(r)
        if e["Residual"] > e["Inherent"]:
            errs.append(f"{rid}: residual score {e['Residual']} is higher than inherent {e['Inherent']}")
        if r["Treatment"] == "Accept" or r["Status"] == "Accepted":
            exp = (r.get("AcceptanceExpiry") or "").strip()
            if not exp:
                errs.append(f"{rid}: accepted risk needs an AcceptanceExpiry date")
            elif date.fromisoformat(exp) < today:
                errs.append(f"{rid}: risk acceptance expired {exp}")
    return errs


def heatmap(rows: list[dict], key_l: str, key_i: str) -> str:
    grid = {(l, i): [] for l in range(1, 6) for i in range(1, 6)}
    for r in rows:
        grid[(int(r[key_l]), int(r[key_i]))].append(r["RiskId"])
    lines = ["| Likelihood ↓ / Impact → | 1 | 2 | 3 | 4 | 5 |", "|---|---|---|---|---|---|"]
    for l in range(5, 0, -1):
        cells = []
        for i in range(1, 6):
            ids = grid[(l, i)]
            band = rating(l * i)
            mark = {"Critical": "🟥", "High": "🟧", "Medium": "🟨", "Low": "🟩"}[band]
            cells.append(f"{mark} {', '.join(ids)}" if ids else mark)
        lines.append(f"| **{l}** | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def report(rows: list[dict]) -> str:
    rows = [enrich(r) for r in rows]
    over = [r for r in rows if r["Residual"] > APPETITE]
    top = sorted(rows, key=lambda r: (-r["Inherent"], r["RiskId"]))
    out = ["# Risk register report", "",
           f"Generated by `tools/risk_report.py`. {len(rows)} risks · appetite: residual ≤ {APPETITE} (Medium).", "",
           "## Inherent risk heat map", "", heatmap(rows, "Likelihood", "Impact"), "",
           "## Residual risk heat map (after recommended controls)", "", heatmap(rows, "ResidualLikelihood", "ResidualImpact"), "",
           "## Risks by inherent score", "",
           "| ID | Risk | C/I/A | Inherent | Residual | Treatment | Owner | Status |", "|---|---|---|---|---|---|---|---|"]
    for r in top:
        cia = "/".join(x[0] for x in (r["Confidentiality"], r["Integrity"], r["Availability"]))
        out.append(f"| {r['RiskId']} | {r['Title']} | {cia} | {r['Inherent']} {r['InherentRating']} | "
                   f"{r['Residual']} {r['ResidualRating']} | {r['Treatment']} | {r['Owner']} | {r['Status']} |")
    out += ["", "## Above appetite after treatment", ""]
    out += [f"- **{r['RiskId']}** {r['Title']}: residual {r['Residual']} ({r['ResidualRating']})" for r in over] or ["None."]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("register", type=Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--today", type=date.fromisoformat, default=date.today())
    args = ap.parse_args(argv)
    rows = load(args.register)
    errs = validate(rows, args.today)
    if errs:
        print("\n".join(errs))
        return 1
    if not args.check:
        (args.register.parent / "REPORT.md").write_text(report(rows), encoding="utf-8")
    print(f"OK: {len(rows)} risks valid")
    return 0


if __name__ == "__main__":
    sys.exit(main())
